//! 候选文本的确定性净化（与来源无关）：隐藏块 / 图片引用 / harness 套话前缀 / 前导 markdown 标记。
//!
//! # 为什么在标题域
//!
//! 这些步骤是**标题素材**的清理（`conversation` 侧曾用 `NormTarget::Title` 表达），而标题判决
//! 现在两个消费者共用（历史列表 + 实时侧栏）。留在 `conversation` 只会让实时侧栏拿不到 ——
//! 实测后果：首条用户消息里的 `<system-reminder>` 与 `[[Image #1]](file://…)` 会原样变成标题。
//!
//! # 与 `transcript_noise` 的分工
//!
//! 「哪些字节不是语义」的事实（隐藏块词表、注释 / 图片 / 套话剥离）由
//! [`crate::common::agent::transcript_noise`] 独占一份，预览管线消费同一份实现
//! （两张逐字重复的词表 + 两份隐藏块移除实现曾各自漂移，其中一份还会 panic）。
//! 本文件只保留**标题特有**的那一步（前导 markdown 标记）与流水线顺序。
//!
//! # 边界
//!
//! 输入已由调用方按净化窗口（`text::TITLE_CLEAN_BUDGET_CHARS`）截好：本函数不做预算，
//! 也不做判决（判不判负、多长截断是 `judge` / `text` 的事），
//! 也不改写语义（不摘要、不翻译）—— 与 `judge` 同一条「客户端只做拒绝」原则。

use crate::common::agent::transcript_noise::{
    strip_harness_sentence_prefixes, strip_hidden_blocks, strip_html_comments,
    strip_image_references,
};

/// 净化一条候选文本（幂等：多跑几次结果不变）。
///
/// 顺序只有语义上的理由，不是随意排列：
///
/// 1. 隐藏块 / 注释 / 图片 / 套话 —— 删掉「不是人写的字」；
/// 2. markdown 标记 —— 只在标题形态里有意义（`# Check Agent Task` 的开头 `#`）；
/// 3. 空白折叠 —— 放到最后，因为上面每一步都可能留下连续空格。
#[must_use]
pub(super) fn clean(raw: &str) -> String {
    let stripped = strip_hidden_blocks(raw);
    let without_prefix = strip_harness_sentence_prefixes(&stripped);
    let without_heading = strip_leading_markdown_heading(without_prefix);
    let without_comments = strip_html_comments(without_heading);
    let without_images = strip_image_references(&without_comments);
    without_images
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

/// 剥掉前导 markdown 标题标记（`# ` / `## ` / `### `）。
///
/// 只在这里做、不在预览管线里做：预览保留原格式是有用的上下文，标题里 `#` 只是噪声。
fn strip_leading_markdown_heading(text: &str) -> &str {
    let trimmed = text.trim();
    if trimmed.starts_with("# ") || trimmed.starts_with("## ") || trimmed.starts_with("### ") {
        return trimmed.trim_start_matches('#').trim_start();
    }
    trimmed
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn removes_hidden_blocks_and_keeps_the_sentence_around_them() {
        assert_eq!(
            clean("Fix the <system-reminder>please do X</system-reminder> login bug"),
            "Fix the login bug"
        );
        assert_eq!(
            clean("Plan <codex_internal_context>secret</codex_internal_context> the work"),
            "Plan the work"
        );
    }

    /// 没终止符就**不要**吞掉后面全部正文（真实 prompt 可能只是引用了这个标签名）。
    #[test]
    fn leaves_unterminated_blocks_alone() {
        assert_eq!(
            clean("compare <thinking with our impl"),
            "compare <thinking with our impl"
        );
    }

    /// 同前缀标签不能被当成目标标签（`<thinking-foo>` ≠ `<thinking>`）。
    #[test]
    fn does_not_match_lookalike_tags() {
        let text = "<thinking-notes>keep me</thinking-notes>";
        assert_eq!(clean(text), "<thinking-notes>keep me</thinking-notes>");
    }

    #[test]
    fn strips_image_references_and_html_comments() {
        assert_eq!(
            clean("[[Image #1]](file:///Users/t/blobs/32b9.png)\n\n图片显示不对"),
            "图片显示不对"
        );
        assert_eq!(clean("[Image #1] 看这个 bug"), "看这个 bug");
        assert_eq!(clean("修复 <!-- TODO --> 登录"), "修复 登录");
    }

    #[test]
    fn strips_harness_sentence_prefixes_and_markdown_headings() {
        assert_eq!(
            clean("Caveat: The messages below were generated by the user while running local commands. real request"),
            "real request"
        );
        assert_eq!(
            clean("# Check Agent Task\nYou are the Check Agent"),
            "Check Agent Task You are the Check Agent"
        );
    }

    /// **回归（2026-11-10 panic）**：净化必须扛住「小写展开改变字节数」的字符。
    /// 旧实现把 `to_lowercase()` 的偏移用在原文上 —— 这里既断言不 panic，也断言结果干净。
    #[test]
    fn survives_characters_whose_lowercase_changes_byte_length() {
        assert_eq!(
            clean("İİ <thinking>x</thinking> fix the parser"),
            "İİ fix the parser"
        );
        assert_eq!(clean("İ <system-reminder>a</system-reminder> b"), "İ b");
        assert_eq!(clean("ẞ <thinking>x</thinking>"), "ẞ");
        // 极端形态：多块 + 多字节字符（旧实现在这里越界）
        assert_eq!(
            clean("İİİİİİİİİİ <thinking>a</thinking> <thinking>b</thinking> tail"),
            "İİİİİİİİİİ tail"
        );
    }

    /// 幂等：净化两次与一次结果相同（否则「同一候选两个消费者拿到不同文本」）。
    #[test]
    fn clean_is_idempotent() {
        let once = clean("  Fix  the <thinking>x</thinking> bug  ");
        assert_eq!(clean(&once), once);
    }
}
