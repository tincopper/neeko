//! 转录文本里的**非语义片段**：隐藏块 / HTML 注释 / 图片引用 / harness 句子前缀。
//!
//! # 为什么独立成模块（第一性原理）
//!
//! 「哪些字节不是人写的语义」是**转录格式的事实**，与「拿这段文本做什么」无关。它有两个
//! 消费者，分属两个域：
//!
//! | 消费者 | 用途 |
//! | --- | --- |
//! | [`super::title::clean`] | 标题素材（`admit` 的第一步） |
//! | [`crate::conversation::normalize`] | 列表预览 |
//!
//! 放在任一侧都会让另一侧反向依赖。各自抄一份的代价已经付过两次：① 两张词表逐字重复；
//! ② 隐藏块移除被手写两遍，其中一份**在 `to_lowercase()` 的字节索引上切原文** —— 遇到
//! `İ` / `ẞ` 这类「小写展开后字节数改变」的字符会 `panic` 或静默吃掉正文（2026-11-10 实测）。
//! 所以这里只保留一份**索引安全**的实现。
//!
//! # 索引安全（为什么用正则而不是手写扫描器）
//!
//! 大小写不敏感匹配需要「折叠大小写后的副本」，而那个副本的字节偏移**与原文无关**
//! （`İ` 2B → `i̇` 3B）。任何「在 lower 上找位置、在原文上切片」的写法都是错的。
//! 正则引擎内部按字符边界推进，天然不会混用两套偏移。
//!
//! # 边界
//!
//! 只做**删除**：不摘要、不改写、不猜。「这条消息要不要整条丢弃」「这段文本配不配当标题」
//! 都是策略，留在各自的域里（`normalize::is_harness_injected_user_turn`、`title::admit`）。

// 静态正则字面量的 `expect`：与运行时输入无关（写错就是编译期常量写错）。
// 与 `conversation/normalize.rs` / `conversation/text.rs` 同一先例，只在本文件放开这个 lint。
#![allow(clippy::expect_used)]

use std::sync::LazyLock;

use regex::{escape, Regex};

/// 已知隐藏块标签对（大小写不敏感），整段移除 `<tag>…</tag>`。
///
/// 名单来自实测转录（orca 的 `HIDDEN_TEXT_BLOCKS` 同源）：这些块是 harness 塞给模型的
/// 上下文，不是用户的字。
pub const HIDDEN_BLOCKS: &[(&str, &str)] = &[
    ("system-reminder", "</system-reminder>"),
    ("codex_internal_context", "</codex_internal_context>"),
    ("goal_context", "</goal_context>"),
    ("thinking", "</thinking>"),
];

/// harness 注入的句子级前缀（剥掉前缀、保留其余正文）。
///
/// 与「整条丢弃」的词表（`normalize::HARNESS_INJECTED_PREFIXES`）**语义不同**：这里只剥
/// 一句套话，剩下的真需求仍然是素材，所以两张表不合并。
pub const HARNESS_SENTENCE_PREFIXES: &[&str] = &[
    "caveat: the messages below were generated by the user while running local commands",
    "this session is being continued from a previous conversation",
];

/// 每对隐藏块的编译后正则（进程内编译一次）。
///
/// `(?:\s[^>]*)?` 让 `<tag attr="…">` 也命中，同时**拒绝** `<tag-other>`（同前缀的假标签）。
static HIDDEN_BLOCK_RES: LazyLock<Vec<Regex>> = LazyLock::new(|| {
    HIDDEN_BLOCKS
        .iter()
        .map(|(open, close)| {
            Regex::new(&format!(
                r"(?is)<{}(?:\s[^>]*)?>.*?{}",
                escape(open),
                escape(close)
            ))
            .expect("infallible: static regex built from static tag names")
        })
        .collect()
});

/// HTML 注释：`<!-- … -->` 是给模型看的标注，不是标题 / 预览素材。
static HTML_COMMENT: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?s)<!--.*?-->").expect("infallible: static pattern"));

/// 图片引用：markdown 图片与 harness 占位式引用。
///
/// 覆盖两种真实形态（pi / claude 会话里都存在）：
/// - `[[Image #1]](file:///…/blobs/<sha>.png)`、`[Image #1](url)`、`[Image #1]`
/// - `![alt](url)`
///
/// 图片指向附件而非语义文本：留在标题里只会得到一长串 blob URI。**正文**不做此处理
/// （正文里的图片链接对用户仍有价值）。
static IMAGE_REFERENCE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(?i)!?\[+Image\s*#\d+\]+(?:\([^)]*\))?|!\[[^\]]*\]\([^)]*\)")
        .expect("infallible: static pattern")
});

/// 整段移除隐藏块（大小写不敏感；终止符缺失时不动 —— 宁可留着也不吞掉正文）。
#[must_use]
pub fn strip_hidden_blocks(text: &str) -> String {
    HIDDEN_BLOCK_RES.iter().fold(text.to_string(), |acc, re| {
        re.replace_all(&acc, "").into_owned()
    })
}

/// 移除 HTML 注释（替换为一个空格：注释两侧通常是词边界）。
#[must_use]
pub fn strip_html_comments(text: &str) -> String {
    HTML_COMMENT.replace_all(text, " ").into_owned()
}

/// 剥离图片引用（替换为一个空格，理由同上）。
#[must_use]
pub fn strip_image_references(text: &str) -> String {
    IMAGE_REFERENCE.replace_all(text, " ").into_owned()
}

/// 剥掉已知 harness 句子级前缀（只剥前缀，正文原样返回）。
///
/// 大小写比较用 `to_ascii_lowercase()`：它**逐字节等同**（ASCII 折叠），因此可以在它上面
/// 求前缀长度并安全地切原文 —— 这正是 `to_lowercase()` 做不到的事（见模块头）。
#[must_use]
pub fn strip_harness_sentence_prefixes(text: &str) -> &str {
    let lower = text.to_ascii_lowercase();
    for prefix in HARNESS_SENTENCE_PREFIXES {
        let Some(rest) = lower.strip_prefix(prefix) else {
            continue;
        };
        // 前缀后必须是句子分隔符或空白，否则 `Caveat:xyz` 这种粘连词不该被剥。
        if rest.is_empty() || rest.starts_with(['.', ' ', ',', '!']) {
            return text[prefix.len()..].trim_start_matches(['.', ' ', ',', '!']);
        }
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 只做删除：留下的连续空格由调用方的折叠步骤处理（`clean` / `collapse_whitespace`）。
    #[test]
    fn removes_hidden_blocks_but_keeps_the_sentence_around_them() {
        assert_eq!(
            strip_hidden_blocks("Fix the <system-reminder>please do X</system-reminder> login bug"),
            "Fix the  login bug"
        );
        assert_eq!(
            strip_hidden_blocks("Plan <codex_internal_context>secret</codex_internal_context> it"),
            "Plan  it"
        );
    }

    /// 隐藏块标签可能带属性（`<goal_context id="…">`），也必须整段移除。
    #[test]
    fn removes_hidden_blocks_with_attributes() {
        assert_eq!(
            strip_hidden_blocks(r#"A <goal_context id="g1" scope='x'>drop me</goal_context> B"#),
            "A  B"
        );
    }

    /// 大小写不敏感：CLI 有时把标签写成全大写。
    #[test]
    fn removes_hidden_blocks_case_insensitively() {
        assert_eq!(strip_hidden_blocks("x <THINKING>drop</thinking> y"), "x  y");
    }

    /// 没终止符就**不要**吞掉后面全部正文（真实 prompt 可能只是引用了这个标签名）。
    #[test]
    fn leaves_unterminated_blocks_alone() {
        assert_eq!(
            strip_hidden_blocks("compare <thinking with our impl"),
            "compare <thinking with our impl"
        );
    }

    /// 同前缀标签不能被当成目标标签（`<thinking-notes>` ≠ `<thinking>`）。
    #[test]
    fn does_not_match_lookalike_tags() {
        let text = "<thinking-notes>keep me</thinking-notes>";
        assert_eq!(strip_hidden_blocks(text), text);
    }

    /// **回归（2026-11-10 panic）**：`İ`（U+0130）的小写展开是 2 个字符 / 3 个字节，
    /// 与原文不等长。任何「在 lower 上求偏移、在原文上切片」的实现都会在这里越界或吃字。
    #[test]
    fn survives_characters_whose_lowercase_changes_byte_length() {
        for text in [
            "İİİİİİİİİİ <thinking>x</thinking>",
            "İİ <thinking>a</thinking> <thinking>b</thinking>",
            "ẞ <thinking>x</thinking>",
            "İ <system-reminder>a</system-reminder> b",
        ] {
            // 唯一判据：不 panic，且标签本身不再出现在结果里。
            let out = strip_hidden_blocks(text);
            assert!(!out.contains("thinking>") && !out.contains("system-reminder>"));
        }
        assert_eq!(
            strip_hidden_blocks("İİ <thinking>x</thinking> fix"),
            "İİ  fix"
        );
    }

    /// 注释移除只保证「注释消失、两侧词不粘连」，空格数量由调用方的折叠步骤决定。
    #[test]
    fn strips_html_comments() {
        assert_eq!(
            strip_html_comments("修复 <!-- TODO --> 登录")
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" "),
            "修复 登录"
        );
        assert_eq!(
            strip_html_comments("a<!-- x -->b")
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" "),
            "a b"
        );
    }

    #[test]
    fn strips_image_references_in_both_forms() {
        assert_eq!(
            strip_image_references("[[Image #1]](file:///Users/t/blobs/32b9.png)\n\n图片显示不对"),
            " \n\n图片显示不对"
        );
        assert_eq!(
            strip_image_references("[Image #1] 看这个 bug"),
            "  看这个 bug"
        );
        assert_eq!(strip_image_references("![shot](a.png) 正文"), "  正文");
    }

    #[test]
    fn peels_harness_sentence_prefixes_and_keeps_the_chinese_body() {
        assert_eq!(
            strip_harness_sentence_prefixes(
                "Caveat: The messages below were generated by the user while running local commands. real request"
            ),
            "real request"
        );
        // 大小写不敏感（ASCII 折叠）
        assert_eq!(
            strip_harness_sentence_prefixes("CAVEAT: THE MESSAGES BELOW WERE GENERATED BY THE USER WHILE RUNNING LOCAL COMMANDS! 正文"),
            "正文"
        );
        // 粘连词不剥（`Caveat:xyz` 不是那句话）
        assert_eq!(
            strip_harness_sentence_prefixes("Caveat:xyz 正文"),
            "Caveat:xyz 正文"
        );
    }

    /// 前缀剥离也必须扛住「小写展开改变长度」的字符（同族回归）。
    #[test]
    fn prefix_peeling_never_slices_a_lowercased_offset() {
        let text = "İİ <thinking>x</thinking>";
        assert_eq!(strip_harness_sentence_prefixes(text), text);
    }
}
